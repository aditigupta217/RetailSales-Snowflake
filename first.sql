CREATE OR REPLACE TABLE CAPSTONE_DB.GOLD.GOLD_DISCOUNT_ANALYSIS AS
SELECT
    DISCOUNT,
    COUNT(*) AS TOTAL_ORDERS,
    SUM(SALES) AS TOTAL_SALES,
    SUM(PROFIT) AS TOTAL_PROFIT,
    AVG(PROFIT) AS AVERAGE_PROFIT
FROM CAPSTONE_DB.SILVER.SLV_SUPERSTORE
GROUP BY DISCOUNT
ORDER BY DISCOUNT;

