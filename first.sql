CREATE OR REPLACE TABLE CAPSTONE_DB.GOLD.GOLD_TOP_PRODUCTS AS
SELECT
    PRODUCT_NAME,
    CATEGORY,
    SUM(SALES) AS TOTAL_SALES,
    SUM(PROFIT) AS TOTAL_PROFIT,
    SUM(QUANTITY) AS TOTAL_QUANTITY
FROM CAPSTONE_DB.SILVER.SLV_SUPERSTORE
GROUP BY PRODUCT_NAME, CATEGORY
ORDER BY TOTAL_PROFIT DESC
LIMIT 10;

CREATE OR REPLACE TABLE CAPSTONE_DB.GOLD.GOLD_STATE_ANALYSIS AS
SELECT
    STATE,
    REGION,
    SUM(SALES) AS TOTAL_SALES,
    SUM(PROFIT) AS TOTAL_PROFIT,
    SUM(QUANTITY) AS TOTAL_QUANTITY
FROM CAPSTONE_DB.SILVER.SLV_SUPERSTORE
GROUP BY STATE, REGION
ORDER BY TOTAL_SALES DESC;

CREATE OR REPLACE TABLE CAPSTONE_DB.GOLD.GOLD_MONTHLY_PROFIT AS
SELECT
    YEAR(ORDER_DATE) AS SALES_YEAR,
    MONTH(ORDER_DATE) AS SALES_MONTH,
    SUM(SALES) AS TOTAL_SALES,
    SUM(PROFIT) AS TOTAL_PROFIT,
    SUM(QUANTITY) AS TOTAL_QUANTITY
FROM CAPSTONE_DB.SILVER.SLV_SUPERSTORE
GROUP BY YEAR(ORDER_DATE), MONTH(ORDER_DATE)
ORDER BY SALES_YEAR, SALES_MONTH;

