CREATE OR REPLACE TABLE SLV_SUPERSTORE AS

SELECT
    TRY_TO_NUMBER(ROW_ID) AS ROW_ID,

    TRIM(ORDER_ID) AS ORDER_ID,

    TRY_TO_DATE(ORDER_DATE, 'MM/DD/YYYY') AS ORDER_DATE,

    TRY_TO_DATE(SHIP_DATE, 'MM/DD/YYYY') AS SHIP_DATE,

    TRIM(SHIP_MODE) AS SHIP_MODE,

    TRIM(CUSTOMER_ID) AS CUSTOMER_ID,

    TRIM(CUSTOMER_NAME) AS CUSTOMER_NAME,

    TRIM(SEGMENT) AS SEGMENT,

    TRIM(COUNTRY) AS COUNTRY,

    TRIM(CITY) AS CITY,

    TRIM(STATE) AS STATE,

    NULLIF(TRIM(POSTAL_CODE), '') AS POSTAL_CODE,

    TRIM(REGION) AS REGION,

    TRIM(PRODUCT_ID) AS PRODUCT_ID,

    TRIM(CATEGORY) AS CATEGORY,

    TRIM(SUB_CATEGORY) AS SUB_CATEGORY,

    TRIM(PRODUCT_NAME) AS PRODUCT_NAME,

    TRY_TO_DECIMAL(SALES, 12, 2) AS SALES,

    TRY_TO_NUMBER(QUANTITY) AS QUANTITY,

    TRY_TO_DECIMAL(DISCOUNT, 5, 2) AS DISCOUNT,

    TRY_TO_DECIMAL(PROFIT, 12, 2) AS PROFIT,

    LOAD_TIMESTAMP,
    BATCH_ID,
    SOURCE_FILE

FROM CAPSTONE_DB.BRONZE.SUPERSTORE_RAW

QUALIFY ROW_NUMBER() OVER (
    PARTITION BY ROW_ID
    ORDER BY LOAD_TIMESTAMP DESC
) = 1;


SELECT COUNT(*) AS TOTAL_RECORDS
FROM CAPSTONE_DB.SILVER.SLV_SUPERSTORE;

SELECT
    ROW_ID,
    ORDER_DATE,
    SHIP_DATE,
    SALES,
    QUANTITY,
    DISCOUNT,
    PROFIT
FROM CAPSTONE_DB.SILVER.SLV_SUPERSTORE
LIMIT 10;

